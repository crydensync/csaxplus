import type { Metadata } from "next";
import { redirect } from "next/navigation";

import { readSession } from "@/server/auth/guard";

import { ConsoleTopbar } from "../console-topbar";
import { SignOutButton } from "../sign-out-button";
import { DigestView } from "./digest-view";
import { DigestScheduleView } from "./schedule-view";

export const metadata: Metadata = { title: "Weekly Digest" };

export default async function DigestPage() {
  const session = await readSession();
  if (session === null) redirect("/login");
  return (
    <>
      <ConsoleTopbar
        title="Weekly Digest"
        subtitle="Stored reports generated by the CSAG digest worker."
        actions={<SignOutButton csrf={session.csrf} />}
      />
      <DigestScheduleView csrf={session.csrf} />
      <DigestView />
    </>
  );
}
